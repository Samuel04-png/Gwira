export function SkillGlyph({ skill, large = false }: { skill: { id: string; name: string }; large?: boolean }): React.ReactElement {
  const key = `${skill.id} ${skill.name}`.toLowerCase();
  const name: IconName = key.includes('pdf') ? 'file' : key.includes('image') ? 'image' : key.includes('review') ? 'code-review' : key.includes('plugin') ? 'plugin' : 'skills';
  return <span className={`skill-icon ${large ? 'large' : ''}`}><Icon name={name} size={large ? 20 : 16} /></span>;
}
