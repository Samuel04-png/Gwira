export type IconName = keyof typeof iconRegistry;
export type ShellIconKey = IconName;
export type IconSize = 14 | 16 | 18 | 20 | 24;
export interface IconProps { name: IconName; size?: IconSize; className?: string }
/** Decorative glyphs inherit color; their host owns the accessible action name. */
export function Icon({ name, size = 16, className = '' }: IconProps): React.ReactElement {
  if (name === 'sidebar-collapse' || name === 'sidebar-expand') {
    const Glyph = name === 'sidebar-collapse' ? PanelLeftClose : PanelLeftOpen;
    return <Glyph className={`gw-icon ${className}`} size={`var(--gw-icon-size-${size})`} strokeWidth={1.5} data-icon={name} aria-hidden="true" focusable="false" />;
  }
  const Glyph = iconRegistry[name];
  return <Glyph className={`gw-icon ${className}`} size={`var(--gw-icon-size-${size})`} weight="regular" mirrored={name==='inspector'}
    data-icon={name} aria-hidden="true" focusable="false" />;
}
export function NavigationIcon({ name, active = false, size = 18, className = '' }: {
  name: keyof typeof navigationIconRegistry; active?: boolean; size?: IconSize; className?: string;
}): React.ReactElement {
  const Glyph = navigationIconRegistry[name], weight = navigationIconWeight(name,active);
  return <Glyph className={`gw-icon gw-navigation-icon ${className}`} size={`var(--gw-icon-size-${size})`} weight={weight}
    data-navigation-icon={name} data-icon-selected={active} data-icon-variant={weight==='fill'?'solid':'outline'}
    aria-hidden="true" focusable="false" />;
}
export function ShellIcon({ name, size = 18, className = 'shell-icon' }: IconProps): React.ReactElement {
  return <Icon name={name} size={size} className={className} />;
}
